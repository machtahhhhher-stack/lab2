"""Регулярные выражения для цветов в формате HEX.

Допустимые формы записи (как в CSS):
    #RGB       - короткая запись, например #f0a
    #RGBA      - короткая с прозрачностью, #f0a8
    #RRGGBB    - полная запись, #ff00aa
    #RRGGBBAA  - полная с прозрачностью, #ff00aa80
Регистр букв не важен: #FF00AA и #ff00aa - один и тот же цвет.
"""
import re

# Сами цифры цвета. Длинные варианты стоят первыми: регулярка перебирает
# альтернативы слева направо, и иначе в "#ff00aa" нашлось бы только "#ff0".
HEX_DIGITS = r"(?:[0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{4}|[0-9a-f]{3})"

# Проверка строки целиком. match() привязывает начало к началу строки,
# а \Z - конец к концу, поэтому лишних символов быть не может.
VALID_COLOR = re.compile(rf"\#{HEX_DIGITS}\Z", re.IGNORECASE)

# Поиск цветов внутри произвольного текста (CSS, HTML, обычный текст).
SEARCH_COLOR = re.compile(
    rf"""
    (?<![\w&\#])      # перед решёткой не буква/цифра (C#, page#top),
                      # не & (в HTML &#123; - это код символа) и не вторая #
    \#                # сама решётка
    ({HEX_DIGITS})    # группа 1 - цифры цвета
    (?!\w)            # после цвета не идёт буква/цифра: в "#abcz" цвета нет
    """,
    re.IGNORECASE | re.VERBOSE,
)

# Разделители, которыми пользователь может перечислить несколько цветов
SEPARATORS = re.compile(r"[,;\s]+")

# Одна шестнадцатеричная цифра - нужна, чтобы развернуть #f0a в #ff00aa
ONE_DIGIT = re.compile(r"([0-9a-f])", re.IGNORECASE)

# Две цифры подряд - один канал цвета (красный, зелёный, синий, альфа)
CHANNEL = re.compile(r"[0-9a-f]{2}", re.IGNORECASE)
